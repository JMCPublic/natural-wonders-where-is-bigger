#!/usr/bin/env python3
"""Shared builder for translated pages (French, Spanish, and later ones).
A language file (build_fr.py, build_es.py) supplies its own wording for every English string listed in
en_strings.json, in the same order, and langkit swaps them in. Each swap must match the expected number
of times, so a change to the English page that would leave a half-translated page stops the build."""
import json, re, os, sys
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
EN=json.load(open(os.path.join(HERE,'en_strings.json'),encoding='utf-8'))
def build(C):
    s=open(os.path.join(ROOT,'index.html'),encoding='utf-8').read()
    n=[0]
    def rep(old,new,count=1):
        nonlocal s
        c=s.count(old)
        if c!=count: sys.exit(f"build_{C['code']}: expected {count}x but found {c}x of:\n  {old[:120]}")
        s=s.replace(old,new); n[0]+=1
    names=C['names']
    s,k=re.subn(r'"id": "([A-Z]{3})", "n": "([^"]*)"',lambda m:'"id": "%s", "n": "%s"'%(m.group(1),names.get(m.group(1),m.group(2)).replace('"','\\"')),s)
    if k<150: sys.exit('country names not found')
    s=re.sub(r'"cap": "([^"]*)"',lambda m:'"cap": "%s"'%C['caps'].get(m.group(1),m.group(1)),s)
    T=C['T']
    if len(T)!=len(EN['reps']): sys.exit(f"build_{C['code']}: {len(T)} translations for {len(EN['reps'])} strings")
    for (old,cnt),new in zip(EN['reps'],T):
        if old.startswith('<title>'): new=new+'\n'+C['head']
        rep(old,new,cnt)
    for a,b in zip(EN['V'],C['V']): rep(a,b,2)
    for a,b in zip(EN['FB'],C['FB']): rep(a,b)
    i=s.index('<p class="gf">'); j=s.index(C['sources_end'])
    block=s[i:j]
    for a,b in zip(EN['SRC'],C['SRC']):
        if block.count(a)!=1: sys.exit('sources text changed: '+a[:60])
        block=block.replace(a,b)
    block=re.sub(r'\. See (<a [^>]*>)',r'. '+C['see']+r' \1',block)
    s=s[:i]+block+s[j:]
    for a,b,c in C.get('extra',[]): rep(a,b,c)
    # open on the home region the first time, remembered per language afterwards
    rep("localStorage.getItem('wib_settings')",f"localStorage.getItem('wib_settings_{C['code']}')")
    rep("localStorage.setItem('wib_settings',",f"localStorage.setItem('wib_settings_{C['code']}',")
    rep("region:'world',layout","region:'home',layout")
    s=s.replace('<!doctype html>',f"<!doctype html>\n<!-- GENERATED by tools/build_{C['code']}.py from ../index.html. Edit the English page, then run the build again. -->",1)
    os.makedirs(os.path.join(ROOT,C['code']),exist_ok=True)
    open(os.path.join(ROOT,C['code'],'index.html'),'w',encoding='utf-8').write(s)
    left=sorted(set(re.findall(r"(?:>|')([A-Z][a-z]+(?: [a-z]+){2,}[.?!]?)(?:<|')",s)))
    print(f"build_{C['code']}: {n[0]} replacements, {k} names. Possible English left:",left[:30])
